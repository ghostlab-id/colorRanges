#' Create a Color Range Between Two Colors
#'
#' Generate a sequence of colors by interpolating between two endpoint
#' colors. If a single color is supplied, that color is repeated.
#'
#' @param color_palette A character vector containing one or two colors in a 
#'   format understood by [grDevices::col2rgb()], such as hexadecimal color 
#'   codes or R color names. With two colors, these define the endpoints of 
#'   the generated range.
#' @param n A positive integer specifying the number of colors to generate.
#' @param single_color Character string defining which color is returned when
#'   `n = 1` and two endpoint colors are supplied. One of `"middle"` (default),
#'   returning the color between both endpoints; `"first"`, returning the 
#'   first endpoint; or `"last"`, returning the second endpoint.
#'
#' @return A character vector of length `n` containing hexadecimal color codes.
#'
#' @details
#' When two endpoint colors are supplied, colors are generated by interpolation
#' between the endpoints using [colorspace::mixcolor()]. Both endpoint colors
#' are included when `n > 1`.
#'
#' When only one color is supplied, it is repeated `n` times.
#' 
#' When `n = 1` and two endpoint colors are supplied, `single_color` determines
#' which color represents the range. By default, the midpoint between both
#' endpoint colors is returned.
#'
#' @examples
#' # Define a set of colors between two endpoints
#' create_color_range(c("#2166AC", "#B2182B"), 5)
#'
#' # Assign a color to multiple entries
#' create_color_range("steelblue", 3)
#' 
#' # Select a single color from a range
#' create_color_range(c("#2166AC", "#B2182B"), 1)
#' create_color_range(c("#2166AC", "#B2182B"), 1, single_color = "first")
#' create_color_range(c("#2166AC", "#B2182B"), 1, single_color = "last")
#'
#' @export
create_color_range <- function(color_palette, n, single_color="middle") {
  
  single_color <- match.arg(single_color, choices = c("first", "last", "middle"))
  
  if (!is.character(color_palette) || !length(color_palette) %in% c(1L, 2L) || anyNA(color_palette)) {
    stop("`color_palette` must contain one or two valid colors.", call. = FALSE)}
  
  color_palette <- validate_color(color=color_palette, name_color= "color_palette")
  
  if (length(n) != 1L || !is.numeric(n) || is.na(n) ||
      n < 1 || n != as.integer(n)) {
    stop("`n` must be a positive integer.", call. = FALSE)}
    
  if (length(color_palette) == 1L){
      return(rep(color_palette[[1L]], n))}
        
  if (n == 1L) {
    if (single_color == "first"){
      return(color_palette[[1L]])}
    if (single_color == "middle"){
      return(
        colorspace::hex(
          colorspace::mixcolor(0.5,
            colorspace::hex2RGB(color_palette[[1L]]),
            colorspace::hex2RGB(color_palette[[2L]]))))}
    if (single_color == "last"){
      return(color_palette[[2L]])}}
  
  colorspace::hex(
    colorspace::mixcolor(
      seq(0, 1, length.out = n),
      colorspace::hex2RGB(color_palette[[1L]]),
      colorspace::hex2RGB(color_palette[[2L]])))}
